"""Write the settings tables of docs/config.md from the settings dataclasses.

    uv run python docs/tools/config_table.py          # rewrite the block between the markers
    uv run python docs/tools/config_table.py --check  # exit 1 when docs/config.md is out of date

Every threshold of the libration analysis and the dry-run is a field of `AnalysisSettings` /
`DryRunSettings` (resonances/resonance/analysis/settings.py) with its .env key, default, unit,
meaning and convention flag; the groups are the `# --- ` sections of resonances/.env.dist. The
table is generated so it cannot drift from the code. Work-log tags in the meanings (W20, author
dates, ...) are dropped for the public page.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import fields
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from resonances.resonance.analysis.settings import AnalysisSettings, DryRunSettings, format_value  # noqa: E402

CONFIG_MD = ROOT / 'docs' / 'config.md'
ENV_DIST = ROOT / 'resonances' / '.env.dist'
BEGIN = '<!-- settings-table:begin (generated by docs/tools/config_table.py, do not edit) -->'
END = '<!-- settings-table:end -->'

# Short titles of the .env.dist groups (matched by the start of the group's comment)
TITLES = (
    ('Filter (shared)', 'Filter and cutoff'),
    ('MMR sampling', 'MMR sampling: alias branches and the unwrap'),
    ('Geometry of an angle', 'Geometry: turning points, centre, episodes, jumps'),
    ('Energy relative to the separatrix', 'Energy and the separatrix zone'),
    ('MMR physics', 'MMR physics: response of a, force law, identity, kinematics'),
    ('MMR subresonances', 'MMR subresonances and the owner search'),
    ('MMR strength', 'MMR strength'),
    ('MMR margins', 'MMR margins of the confidence'),
    ('Secular and Lidov-Kozai', 'Secular and Lidov-Kozai angles'),
    ('Confidence (shared)', 'Confidence'),
    ('Dry-run', 'Dry-run'),
)

# Work-log references that mean nothing to a reader: a parenthesis holding one is dropped whole,
# a bare one with its separator.
TAG = (
    r'(?:W\d{1,2}[a-z]?(?: [A-Z]+\d+[a-z]?| R-[A-Z0-9-]+| round [A-Z])?'
    r'|author\b(?!-)[^;,)]*|Codex\b[^;,)]*|R-ALIAS-A|R-[A-Z0-9]+-[A-Z0-9-]+|CS\d+|N\d+|Q\d+[a-z]?)'
)
PAREN_WITH_TAG = re.compile(r'\s*\((?:[^()]|\([^()]*\))*?\b' + TAG + r'(?:[^()]|\([^()]*\))*\)')
BARE_TAG = re.compile(r'(?:[;,]\s*)?\b' + TAG + r'\b:?\s*')


def clean(text: str) -> str:
    text = re.sub(r',?\s*as before W\d{1,2}[a-z]?', '', text)
    text = re.sub(r'\.?\s*Question [A-Z0-9]+ to the author \(W\d+\)', '', text)
    text = PAREN_WITH_TAG.sub('', text)
    text = BARE_TAG.sub(' ', text)
    text = re.sub(r'\s+([;,.:)])', r'\1', text)
    text = re.sub(r'\(\s*\)', '', text)
    text = re.sub(r'\s{2,}', ' ', text).strip(' ;,')
    return text.replace('|', '\\|')


def groups() -> list[tuple[str, list[str]]]:
    """The .env.dist groups of the analysis section, each with its keys in file order."""
    result: list[tuple[str, list[str]]] = []
    inside = False
    for line in ENV_DIST.read_text().splitlines():
        if line.startswith('# ===== Libration analysis'):
            inside = True
            continue
        if not inside:
            continue
        if line.startswith('# --- '):
            head = line[len('# --- ') :]
            if head.startswith('Output of the MMR analysis'):
                break
            title = next((short for prefix, short in TITLES if head.startswith(prefix)), head.split(':')[0])
            result.append((title, []))
        elif line and not line.startswith('#') and '=' in line and result:
            result[-1][1].append(line.split('=', 1)[0].strip())
    return result


def table() -> str:
    by_env = {f.metadata['env']: f for cls in (AnalysisSettings, DryRunSettings) for f in fields(cls)}
    out: list[str] = []
    seen: set[str] = set()
    for title, keys in groups():
        out += [f'### {title}', '', '| key | default | meaning |', '|---|---|---|']
        for key in keys:
            f = by_env.get(key)
            if f is None:
                raise SystemExit(f'{key} is in .env.dist but not a settings field')
            seen.add(key)
            meaning = clean(f.metadata['meaning'])
            unit = f.metadata['unit']
            if unit:
                meaning += f' [{unit}]'
            if f.metadata['convention']:
                meaning += ' *Convention.*'
            default = format_value(f.default)
            out.append(f"| `{key}` | {f'`{default}`' if default else 'empty'} | {meaning} |")
        out.append('')
    # a field documented in another section of .env.dist (MATRIX_*_ORDER_MAX: the Matrices section) is fine
    env_keys = {line.split('=', 1)[0].strip() for line in ENV_DIST.read_text().splitlines() if line and not line.startswith('#')}
    missing = sorted(set(by_env) - seen - env_keys)
    if missing:
        raise SystemExit('settings fields missing from the .env.dist analysis section: ' + ', '.join(missing))
    return '\n'.join(out).rstrip() + '\n'


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='exit 1 when docs/config.md is out of date')
    args = ap.parse_args()
    text = CONFIG_MD.read_text()
    start, end = text.index(BEGIN) + len(BEGIN), text.index(END)
    new = text[:start] + '\n\n' + table() + '\n' + text[end:]
    if args.check:
        if new != text:
            print('docs/config.md is out of date: run `uv run python docs/tools/config_table.py`')
            return 1
        return 0
    CONFIG_MD.write_text(new)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
